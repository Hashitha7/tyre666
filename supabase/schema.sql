create table if not exists public.contact_submissions (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 100),
  email text not null check (char_length(email) <= 254),
  phone text check (phone is null or char_length(phone) <= 40),
  message text not null check (char_length(message) between 10 and 4000),
  status text not null default 'new' check (status in ('new', 'in-progress', 'resolved')),
  internal_notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.fitment_requests (
  id bigint generated by default as identity primary key,
  make text not null check (char_length(make) between 2 and 80),
  model text not null check (char_length(model) between 1 and 80),
  year integer not null check (year between 1950 and 2100),
  variant text check (variant is null or char_length(variant) <= 100),
  email text not null check (char_length(email) <= 254),
  notes text check (notes is null or char_length(notes) <= 1000),
  status text not null default 'new' check (status in ('new', 'in-progress', 'resolved')),
  internal_notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.newsletter_subscriptions (
  id bigint generated by default as identity primary key,
  email text not null unique check (char_length(email) <= 254),
  source text not null default 'home',
  status text not null default 'active' check (status in ('active', 'unsubscribed')),
  created_at timestamptz not null default now()
);

alter table public.contact_submissions enable row level security;
alter table public.fitment_requests enable row level security;
alter table public.newsletter_subscriptions enable row level security;

revoke all on table public.contact_submissions from anon, authenticated;
revoke all on table public.fitment_requests from anon, authenticated;
revoke all on table public.newsletter_subscriptions from anon, authenticated;
